export function localizeSchemeName(name: string | undefined | null, lang: Language): string {
  if (!name || typeof name !== 'string') return '';
  if (lang === 'en') return name;
  const match = SCHEME_NAME_TRANSLATIONS[name];
  if (match && match[lang]) return match[lang];
  
  // Partial substring matching
  for (const [key, val] of Object.entries(SCHEME_NAME_TRANSLATIONS)) {
    if (key && (name.includes(key) || key.includes(name))) {
      if (val[lang]) return val[lang];
    }
  }
  return name;
}

