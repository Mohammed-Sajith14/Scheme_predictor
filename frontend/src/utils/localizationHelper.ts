export function localizeField(fieldName: string, lang: Language): string {
  if (!fieldName) return fieldName;
  if (FIELD_TRANSLATIONS[fieldName] && FIELD_TRANSLATIONS[fieldName][lang]) {
    return FIELD_TRANSLATIONS[fieldName][lang];
  }
  const lower = fieldName.toLowerCase();
  for (const [k, v] of Object.entries(FIELD_TRANSLATIONS)) {
    if (k.toLowerCase() === lower && v[lang]) {
      return v[lang];
    }
  }
  if (COMMON_TERMS[fieldName] && COMMON_TERMS[fieldName][lang]) {
    return COMMON_TERMS[fieldName][lang];
  }
  return fieldName;
}

